package com.nestedforloop;

public class Pattern {
	
	public static void main(String[] args) {
		
		for(int i=1; i<=2; i++) {
			
			for(int j=1; j<=5; j++) {
				
				System.out.print("*");
			}
			System.out.println();
		}
		System.out.println();
		for(int i=1; i<=3; i++) {
			
			for(int j=1; j<=5; j++) {
				
				System.out.print("*");
			}
			System.out.println();
		}
		
		
	}

}
