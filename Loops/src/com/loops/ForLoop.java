package com.loops;

public class ForLoop {
	
	public static void main(String[] args) {
		
		for(int i=1; i<=4; i++) {
			
			System.out.println(i + ":hai");
		}
		for(int i=11;i<=15;i++) {
			
			System.out.println("hai:" + i);
		}
		for(int i=0; i<10;i++) {
			
			System.out.println("hello");
		}
		for(int i=0; i<=9;i++) {
			
			System.out.println("hi...!!!");
		}
		
	}

}
