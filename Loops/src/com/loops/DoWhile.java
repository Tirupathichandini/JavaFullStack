package com.loops;

public class DoWhile {
	
	public static void main(String[] args) {
		
		int i=1;
		do {
			
			System.out.println(i+":hai");
			i++;
		}
		while(i<=5);
		
		//reverse
				System.out.println("Reverse:");
				int j=5;
				do {
					
					System.out.println(j+":hai");
					j--;
				}
				while(j>=1);		
		
	}
	
	

}
