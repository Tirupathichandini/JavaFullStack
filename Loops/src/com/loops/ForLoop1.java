package com.loops;

public class ForLoop1 {

	public static void main(String[] args) {
		
		for(int i=10;i>=1;i--) {
			
			System.out.println(i+":hai");
		}
		
		for(int i=-5;i<=1;i++) {
			
			System.out.println(i+":hai");
		}
		for(int i=5;i>=1;i--) {
			
			System.out.println(i+":hai");
		}
	}
}
